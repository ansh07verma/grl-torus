class RoutingDataset(Dataset):
    """Dataset of (graph_state, current_node, dst_node, optimal_direction) tuples.

    Generated by running the simulator and computing Dijkstra-optimal
    next-hop directions on the live congestion-weighted graph.
    """

    def __init__(
        self,
        node_features_list: List[torch.Tensor],
        edge_index_list: List[torch.Tensor],
        current_indices: List[torch.Tensor],
        dst_indices: List[torch.Tensor],
        labels: List[torch.Tensor],
    ):
        self.node_features_list = node_features_list
        self.edge_index_list = edge_index_list
        self.current_indices = current_indices
        self.dst_indices = dst_indices
        self.labels = labels

    def __len__(self) -> int:
        return len(self.labels)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        return {
            "node_features": self.node_features_list[idx],
            "edge_index": self.edge_index_list[idx],
            "current_indices": self.current_indices[idx],
            "dst_indices": self.dst_indices[idx],
            "labels": self.labels[idx],
        }


def generate_training_data(
    grid_size: int,
    num_snapshots: int = 500,
    injection_rate: float = 0.01,
    sim_duration_ns: float = 5000,
    seed: int = 42,
    samples_per_snapshot: int = 20,
) -> Tuple[List[torch.Tensor], List[torch.Tensor], List[torch.Tensor], List[torch.Tensor], List[torch.Tensor]]:
    """Generate supervised training data from simulator snapshots.

    For each snapshot:
        1. Run simulator briefly to build up congestion
        2. Capture graph state
        3. For random (src, dst) pairs, compute Dijkstra optimal next-hop
        4. Store (graph, src_idx, dst_idx, optimal_direction)

    Args:
        grid_size: Torus size N for N×N.
        num_snapshots: Number of graph snapshots to generate.
        injection_rate: Traffic injection rate.
        sim_duration_ns: How long to run each snapshot simulation.
        seed: Random seed.
        samples_per_snapshot: Number of (src, dst) routing decisions per snapshot.

    Returns:
        (node_features_list, edge_index_list, current_indices, dst_indices, labels)
    """
    logger.info(
        f"Generating training data: grid={grid_size}, "
        f"snapshots={num_snapshots}, samples/snap={samples_per_snapshot}"
    )

    rng = np.random.default_rng(seed)

    node_features_list = []
    edge_index_list = []
    current_indices_list = []
    dst_indices_list = []
    labels_list = []

    all_nodes = [(x, y) for x in range(grid_size) for y in range(grid_size)]

    for snap_idx in range(num_snapshots):
        # Build fresh torus and simulate to create congestion patterns
        snap_seed = seed + snap_idx
        set_global_seed(snap_seed)

        torus = TorusGraph(grid_size)

        # Optionally inject some failures for diversity
        if rng.random() < 0.3:
            failure_rate = rng.uniform(0.02, 0.15)
            torus.inject_link_failures(failure_rate, np.random.default_rng(snap_seed))

        # Run a short simulation to build up congestion
        router = XYRouter()
        sim = TorusSimulator(
            torus, router,
            duration_ns=sim_duration_ns,
            warmup_ns=0,
        )
        traffic_gen = TrafficGenerator(
            pattern="uniform" if rng.random() < 0.5 else "hotspot",
            grid_size=grid_size,
            injection_rate=injection_rate,
            seed=snap_seed,
        )
        sim.run(traffic_gen)

        # Capture graph state
        state = torus.get_graph_state()
        node_features = torch.tensor(state["node_features"], dtype=torch.float32)
        edge_index = torch.tensor(state["edge_index"], dtype=torch.long)
        coord_to_idx = state["coord_to_idx"]

        # Sample (current, dst) pairs and compute optimal next-hop
        current_indices = []
        dst_indices = []
        labels = []

        active_nodes = torus.get_active_nodes()
        if len(active_nodes) < 2:
            continue

        for _ in range(samples_per_snapshot):
            # Random current and destination
            pair_indices = rng.choice(len(active_nodes), size=2, replace=False)
            current_node = active_nodes[pair_indices[0]]
            dst_node = active_nodes[pair_indices[1]]

            # Get optimal next-hop via Dijkstra
            optimal_dir = torus.get_optimal_next_hop(current_node, dst_node)

            if optimal_dir is None:
                continue

            if optimal_dir not in DIRECTION_TO_IDX:
                continue

            current_indices.append(coord_to_idx[current_node])
            dst_indices.append(coord_to_idx[dst_node])
            labels.append(DIRECTION_TO_IDX[optimal_dir])

        if len(labels) == 0:
            continue

        node_features_list.append(node_features)
        edge_index_list.append(edge_index)
        current_indices_list.append(torch.tensor(current_indices, dtype=torch.long))
        dst_indices_list.append(torch.tensor(dst_indices, dtype=torch.long))
        labels_list.append(torch.tensor(labels, dtype=torch.long))

        if (snap_idx + 1) % 100 == 0:
            logger.info(f"  Generated {snap_idx + 1}/{num_snapshots} snapshots")

    logger.info(
        f"Data generation complete: {len(labels_list)} usable snapshots, "
        f"~{sum(len(l) for l in labels_list)} total samples"
    )

    return node_features_list, edge_index_list, current_indices_list, dst_indices_list, labels_list


