"""
Training loops for GNN (supervised) and DQN (reinforcement learning).

Supervised GNN Training:
    1. Generate training data by running SimPy with random traffic
    2. Compute Dijkstra-optimal next-hop labels on congestion-weighted graphs
    3. Train GraphSAGE + routing head with cross-entropy loss

DQN Training:
    1. Use pretrained GNN encoder (frozen or jointly trained)
    2. Train DQN on SimPy environment with GRL reward function
    3. Prioritised Experience Replay for sample efficiency
"""

