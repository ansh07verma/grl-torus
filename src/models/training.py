def train_gnn_supervised(
    grid_size: int = 8,
    num_snapshots: int = 500,
    epochs: int = 100,
    lr: float = 1e-3,
    weight_decay: float = 1e-4,
    batch_size: int = 32,
    patience: int = 10,
    device: str = "cpu",
    checkpoint_dir: str = "results/checkpoints",
    seed: int = 42,
    samples_per_snapshot: int = 20,
    log_dir: Optional[str] = "results/logs",
) -> Dict[str, Any]:
    """Train the GNN routing model with supervised learning.

    Args:
        grid_size: Torus N for N×N.
        num_snapshots: Number of training snapshots.
        epochs: Maximum training epochs.
        lr: Learning rate.
        weight_decay: L2 regularisation.
        batch_size: Not used for graph-level batching (1 graph at a time).
        patience: Early stopping patience.
        device: 'cpu' or 'cuda'.
        checkpoint_dir: Where to save model checkpoints.
        seed: Random seed.
        samples_per_snapshot: Routing samples per graph snapshot.
        log_dir: TensorBoard log directory.

    Returns:
        Dict with training history and best metrics.
    """
    set_global_seed(seed)

    logger.info(f"Starting supervised GNN training on {grid_size}x{grid_size} torus")
    logger.info(f"Device: {device}, LR: {lr}, Epochs: {epochs}, Patience: {patience}")

    # TensorBoard setup
    writer = None
    if log_dir:
        try:
            from torch.utils.tensorboard import SummaryWriter
            log_path = os.path.join(log_dir, f"gnn_supervised_{grid_size}x{grid_size}")
            writer = SummaryWriter(log_path)
            logger.info(f"TensorBoard logging to: {log_path}")
        except ImportError:
            logger.warning("TensorBoard not available, skipping logging")

    # Generate training data
    data = generate_training_data(
        grid_size=grid_size,
        num_snapshots=num_snapshots,
        seed=seed,
        samples_per_snapshot=samples_per_snapshot,
    )
    node_features_list, edge_index_list, current_indices, dst_indices, labels = data

    total_samples = len(labels)
    if total_samples == 0:
        raise ValueError("No training data generated!")

    # Split: 80% train, 10% val, 10% test
    n_train = int(0.8 * total_samples)
    n_val = int(0.1 * total_samples)

    indices = list(range(total_samples))
    rng = np.random.default_rng(seed)
    rng.shuffle(indices)

    train_indices = indices[:n_train]
    val_indices = indices[n_train : n_train + n_val]
    test_indices = indices[n_train + n_val :]

    logger.info(f"Data split: train={len(train_indices)}, val={len(val_indices)}, test={len(test_indices)}")

    # Model
    model = GNNRoutingModel(
        in_channels=8,
        hidden_channels=128,
        embedding_dim=64,
        num_layers=3,
        num_directions=4,
        dropout=0.1,
    ).to(device)

    total_params = sum(p.numel() for p in model.parameters())
    trainable_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    logger.info(f"Model: {total_params} total params, {trainable_params} trainable")

    # Optimizer with cosine annealing
    optimizer = optim.Adam(model.parameters(), lr=lr, weight_decay=weight_decay)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs)

    criterion = nn.CrossEntropyLoss()

    # Training loop
    best_val_loss = float("inf")
    best_val_acc = 0.0
    patience_counter = 0
    history = {
        "train_loss": [],
        "val_loss": [],
        "val_acc": [],
        "lr": [],
    }

    checkpoint_path = Path(checkpoint_dir)
    checkpoint_path.mkdir(parents=True, exist_ok=True)
    best_model_path = checkpoint_path / f"gnn_best_{grid_size}x{grid_size}.pt"

    start_time = time.time()

    for epoch in range(epochs):
        # --- Train ---
        model.train()
        train_loss = 0.0
        train_correct = 0
        train_total = 0

        rng.shuffle(train_indices)

        for idx in train_indices:
            nf = node_features_list[idx].to(device)
            ei = edge_index_list[idx].to(device)
            ci = current_indices[idx].to(device)
            di = dst_indices[idx].to(device)
            lab = labels[idx].to(device)

            optimizer.zero_grad()
            logits = model(nf, ei, ci, di)
            loss = criterion(logits, lab)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            optimizer.step()

            train_loss += loss.item() * len(lab)
            train_correct += (logits.argmax(dim=-1) == lab).sum().item()
            train_total += len(lab)

        avg_train_loss = train_loss / max(train_total, 1)
        train_acc = train_correct / max(train_total, 1)

        # --- Validate ---
        model.eval()
        val_loss = 0.0
        val_correct = 0
        val_total = 0

        with torch.no_grad():
            for idx in val_indices:
                nf = node_features_list[idx].to(device)
                ei = edge_index_list[idx].to(device)
                ci = current_indices[idx].to(device)
                di = dst_indices[idx].to(device)
                lab = labels[idx].to(device)

                logits = model(nf, ei, ci, di)
                loss = criterion(logits, lab)

                val_loss += loss.item() * len(lab)
                val_correct += (logits.argmax(dim=-1) == lab).sum().item()
                val_total += len(lab)

        avg_val_loss = val_loss / max(val_total, 1)
        val_acc = val_correct / max(val_total, 1)

        scheduler.step()
        current_lr = scheduler.get_last_lr()[0]

        # Record history
        history["train_loss"].append(avg_train_loss)
        history["val_loss"].append(avg_val_loss)
        history["val_acc"].append(val_acc)
        history["lr"].append(current_lr)

        # TensorBoard logging
        if writer:
            writer.add_scalar("Loss/train", avg_train_loss, epoch)
            writer.add_scalar("Loss/val", avg_val_loss, epoch)
            writer.add_scalar("Accuracy/train", train_acc, epoch)
            writer.add_scalar("Accuracy/val", val_acc, epoch)
            writer.add_scalar("LR", current_lr, epoch)

        # Early stopping check
        if avg_val_loss < best_val_loss:
            best_val_loss = avg_val_loss
            best_val_acc = val_acc
            patience_counter = 0

            # Save best model
            torch.save({
                "epoch": epoch,
                "model_state_dict": model.state_dict(),
                "optimizer_state_dict": optimizer.state_dict(),
                "val_loss": avg_val_loss,
                "val_acc": val_acc,
                "grid_size": grid_size,
                "config": {
                    "in_channels": 8,
                    "hidden_channels": 128,
                    "embedding_dim": 64,
                    "num_layers": 3,
                },
            }, best_model_path)
        else:
            patience_counter += 1

        if (epoch + 1) % 10 == 0 or patience_counter == 0:
            logger.info(
                f"Epoch {epoch+1:3d}/{epochs}: "
                f"train_loss={avg_train_loss:.4f}, "
                f"val_loss={avg_val_loss:.4f}, "
                f"val_acc={val_acc:.4f}, "
                f"lr={current_lr:.6f}, "
                f"patience={patience_counter}/{patience}"
            )

        if patience_counter >= patience:
            logger.info(f"Early stopping at epoch {epoch+1}")
            break

    elapsed = time.time() - start_time

    # --- Test ---
    model.eval()
    test_correct = 0
    test_total = 0

    with torch.no_grad():
        for idx in test_indices:
            nf = node_features_list[idx].to(device)
            ei = edge_index_list[idx].to(device)
            ci = current_indices[idx].to(device)
            di = dst_indices[idx].to(device)
            lab = labels[idx].to(device)

            logits = model(nf, ei, ci, di)
            test_correct += (logits.argmax(dim=-1) == lab).sum().item()
            test_total += len(lab)

    test_acc = test_correct / max(test_total, 1)

    if writer:
        writer.add_scalar("Accuracy/test", test_acc, epochs)
        writer.close()

    logger.info(
        f"Training complete in {elapsed:.1f}s: "
        f"best_val_loss={best_val_loss:.4f}, "
        f"best_val_acc={best_val_acc:.4f}, "
        f"test_acc={test_acc:.4f}"
    )
    logger.info(f"Best model saved to: {best_model_path}")

    return {
        "best_val_loss": best_val_loss,
        "best_val_acc": best_val_acc,
        "test_acc": test_acc,
        "epochs_trained": len(history["train_loss"]),
        "total_params": total_params,
        "training_time_s": elapsed,
        "checkpoint_path": str(best_model_path),
        "history": history,
    }


